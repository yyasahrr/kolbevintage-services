/**
 * تفکیک کانال خرید (خرده‌فروشی / عمده) در لایهٔ رابط کاربری.
 *
 * ── چرا این فایل وجود دارد ──────────────────────────────────────────────────
 * یافتهٔ D22 ممیزی PROMPT 1: بنر «پرداخت اقساطی (BNPL)» در `ProductPage` و
 * `ProductCard` بدون هیچ قید کانالی رندر می‌شد، در حالی که `VIPPortal` همان
 * `ProductPage` خرده‌فروشی را زیر مسیر `/product/*` سوار می‌کند. نتیجه: اعضای
 * عمده‌فروشی (VIP) هم تبلیغ خرید اقساطی را می‌دیدند.
 *
 * قاعدهٔ حاکم: **BNPL فقط خرده‌فروشی است** (اعتبار خرد). عمده‌فروشی با تسویهٔ
 * اعتباری/انتقالی کار می‌کند و شرایط آن دامنهٔ جداگانه است.
 *
 * این تابع تک‌مرجع حقیقتِ سمت کلاینت است. سرور مستقل از آن عمل می‌کند
 * (`retail-pricing.ts` → `assertPaymentMethodAllowed`) و همیشه مرجع نهایی است؛
 * این فقط مانع *نمایش* وعدهٔ نادرست به کاربر می‌شود.
 */
export type PurchaseChannel = "retail" | "wholesale";

/**
 * آیا قسط‌بندی در این کانال مجاز است؟
 * @param channel کانال خرید جاری؛ پیش‌فرض مولفه‌ها «خرده‌فروشی» است.
 */
export function isInstallmentAvailable(channel: PurchaseChannel): boolean {
  return channel === "retail";
}

